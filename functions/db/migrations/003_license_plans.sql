-- 003_license_plans.sql: license plan catalogue and one license per organization.
--
-- Idempotent. Replaces the free-text commercial agreement model with plan-based
-- licensing:
--   license_plan          reusable plan catalogue (no prices, no colours)
--   organization_license  exactly one row per organization: plan, term, prices
--   license_history       one row per license event, with the dates and prices
--                         in force at that time (plan name and limits are read
--                         from the live license_plan row)
--
-- The old tables commercial_agreement and license_event are dropped only when
-- they are empty. If either still holds rows the migration stops, so no data
-- is removed silently.

DO $$
BEGIN
  IF to_regclass('public.commercial_agreement') IS NOT NULL THEN
    IF EXISTS (SELECT 1 FROM commercial_agreement) THEN
      RAISE EXCEPTION 'commercial_agreement still has rows. Migrate or delete them before running 003_license_plans.sql.';
    END IF;
  END IF;
  IF to_regclass('public.license_event') IS NOT NULL THEN
    IF EXISTS (SELECT 1 FROM license_event) THEN
      RAISE EXCEPTION 'license_event still has rows. Migrate or delete them before running 003_license_plans.sql.';
    END IF;
  END IF;
END $$;

DROP TABLE IF EXISTS license_event;
DROP TABLE IF EXISTS commercial_agreement;

CREATE TABLE IF NOT EXISTS license_plan (
  id           text PRIMARY KEY DEFAULT gen_random_uuid()::text,
  -- Generated by the server: PLN-<12 hex>-<NAME up to 10 upper-case characters>.
  plan_code    text NOT NULL,
  name         text NOT NULL,
  description  text NOT NULL DEFAULT '',
  level        integer NOT NULL,
  max_stores   integer NOT NULL,
  max_users    integer NOT NULL,
  -- active | inactive. Deactivating a plan is a status change, not a delete.
  status       text NOT NULL DEFAULT 'active',
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT license_plan_plan_code_key UNIQUE (plan_code),
  CONSTRAINT license_plan_level_key UNIQUE (level),
  CONSTRAINT license_plan_level_check CHECK (level >= 1),
  CONSTRAINT license_plan_max_stores_check CHECK (max_stores >= 1),
  CONSTRAINT license_plan_max_users_check CHECK (max_users >= 1),
  CONSTRAINT license_plan_status_check CHECK (status IN ('active', 'inactive'))
);

-- Plan names are unique regardless of case.
CREATE UNIQUE INDEX IF NOT EXISTS license_plan_name_lower_key
  ON license_plan (lower(name));

CREATE TABLE IF NOT EXISTS organization_license (
  id                 text PRIMARY KEY DEFAULT gen_random_uuid()::text,
  organization_id    text NOT NULL UNIQUE REFERENCES organization (id) ON DELETE CASCADE,
  plan_id            text NOT NULL REFERENCES license_plan (id) ON DELETE RESTRICT,
  start_date         date NOT NULL,
  expiry_date        date NOT NULL,
  -- One-time price and yearly maintenance price, in INR.
  negotiated_price   double precision NOT NULL CHECK (negotiated_price >= 0),
  maintenance_price  double precision NOT NULL CHECK (maintenance_price >= 0),
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT organization_license_expiry_after_start CHECK (expiry_date > start_date)
);

CREATE TABLE IF NOT EXISTS license_history (
  id                 text PRIMARY KEY DEFAULT gen_random_uuid()::text,
  organization_id    text NOT NULL REFERENCES organization (id) ON DELETE CASCADE,
  -- assigned | plan_changed | commercial_terms_modified | renewed
  event_type         text NOT NULL,
  plan_id            text NOT NULL REFERENCES license_plan (id) ON DELETE RESTRICT,
  start_date         date,
  expiry_date        date,
  negotiated_price   double precision,
  maintenance_price  double precision,
  event_at           timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT license_history_event_type_check CHECK (
    event_type IN ('assigned', 'plan_changed', 'commercial_terms_modified', 'renewed')
  )
);

CREATE INDEX IF NOT EXISTS organization_license_plan_idx
  ON organization_license (plan_id);
CREATE INDEX IF NOT EXISTS license_history_organization_event_idx
  ON license_history (organization_id, event_at DESC);
CREATE INDEX IF NOT EXISTS license_history_plan_idx
  ON license_history (plan_id);

