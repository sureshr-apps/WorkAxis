/// Lifecycle status of a license plan. Only [active] plans can be assigned to
/// an organization or accept a renewal.
enum PlanStatus {
  active,
  inactive;

  String get displayName => switch (this) {
    PlanStatus.active => 'Active',
    PlanStatus.inactive => 'Inactive',
  };

  /// Parses a stored status. Anything other than `active` (including a missing
  /// or unknown value) is treated as inactive: malformed data must never make a
  /// plan assignable.
  static PlanStatus fromString(String? value) =>
      value?.toLowerCase().trim() == 'active'
      ? PlanStatus.active
      : PlanStatus.inactive;
}

/// A reusable license plan: a catalogue template that defines the store and
/// user limits an organization gets while it holds a license on the plan.
///
/// Plans carry no prices. Commercial terms belong to the organization license.
class LicensePlan {
  const LicensePlan({
    required this.id,
    required this.planCode,
    required this.name,
    required this.description,
    required this.level,
    required this.maxStores,
    required this.maxUsers,
    required this.status,
    this.assignedOrganizations = 0,
  });

  /// Internal identifier; never shown to users.
  final String id;

  /// Human-facing identifier generated by the server (`PLN-<hex>-<NAME>`).
  final String planCode;
  final String name;

  /// Empty when the plan has no description.
  final String description;

  /// Position in the upgrade ladder. Unique across plans; higher is larger.
  final int level;
  final int maxStores;
  final int maxUsers;
  final PlanStatus status;

  /// Number of organizations whose license is on this plan.
  final int assignedOrganizations;

  bool get isActive => status == PlanStatus.active;

  LicensePlan copyWith({
    String? id,
    String? planCode,
    String? name,
    String? description,
    int? level,
    int? maxStores,
    int? maxUsers,
    PlanStatus? status,
    int? assignedOrganizations,
  }) {
    return LicensePlan(
      id: id ?? this.id,
      planCode: planCode ?? this.planCode,
      name: name ?? this.name,
      description: description ?? this.description,
      level: level ?? this.level,
      maxStores: maxStores ?? this.maxStores,
      maxUsers: maxUsers ?? this.maxUsers,
      status: status ?? this.status,
      assignedOrganizations:
          assignedOrganizations ?? this.assignedOrganizations,
    );
  }
}
