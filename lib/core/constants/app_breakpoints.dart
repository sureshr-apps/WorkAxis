/// Breakpoints defined by WorkAxis design system and AGENTS.md.
abstract final class AppBreakpoints {
  /// Width below 600dp: Android smartphones (portrait/landscape).
  static const double compactMax = 599.0;

  /// Width 600dp to 839dp: Android tablets portrait and smaller screens.
  static const double mediumMin = 600.0;
  static const double mediumMax = 839.0;

  /// Width 840dp and above: Android tablets landscape, multi-column.
  static const double expandedMin = 840.0;
}
